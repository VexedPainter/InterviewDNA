import React, { useState } from 'react'
import { motion, AnimatePresence } from 'framer-motion'
import { usePageTitle } from '../../hooks/usePageTitle'
import {
  Lightbulb,
  ShieldCheck,
  AlertCircle,
  ExternalLink,
  X,
  FileText,
  Building,
  Calendar,
  Layers,
  Sparkles,
} from 'lucide-react'
import { GlassCard } from '../../components/ui/GlassCard'
import { Badge } from '../../components/ui/Badge'
import { useSessionStore } from '../../store/sessionStore'
import { useQuery } from '@tanstack/react-query'
import { api } from '../../lib/api/client'
import { ArchiveRecord } from '../../lib/api/types'

export const CoachingPage: React.FC = () => {
  usePageTitle('Coaching')
  const { company, role, messages, activeCitationId, setActiveCitationId } = useSessionStore()
  const [selectedRecordId, setSelectedRecordId] = useState<string | null>(
    activeCitationId || null
  )

  // Fetch record details for drawer
  const { data: recordData, isLoading: isRecordLoading } = useQuery<ArchiveRecord>({
    queryKey: ['record', selectedRecordId],
    queryFn: () => api.getArchiveRecord(selectedRecordId!),
    enabled: !!selectedRecordId,
  })

  // Extract coaching tips from recent session messages or use company defaults
  const sessionAdvice = messages.find((m) => m.coaching)?.coaching

  const tips = sessionAdvice?.tips || [
    {
      text: `When answering technical questions for ${company}, always state the naive approach first in under 30 seconds, then immediately transition to two-pointer or hashing optimizations with explicit Big-O trade-offs.`,
      evidence_ids: ['AMA-2025-00832', 'ZOH-2025-00630'],
      evidence_year: [2025, 2024],
    },
    {
      text: 'In behavioral and managerial rounds, structure your stories strictly with STAR. Historical feedback shows candidates lose up to 40% of marks when they omit quantitative business impact.',
      evidence_ids: ['DEL-2021-01271'],
      evidence_year: [2021],
    },
    {
      text: 'For Database questions, avoid generic answers like "indexes make queries fast". Discuss B-Tree depths, write amplification, and composite index column order.',
      evidence_ids: ['TCS-2025-00200'],
      evidence_year: [2025],
    },
  ]

  const noEvidenceNotice = sessionAdvice?.no_evidence_notice

  return (
    <div className="pt-24 pb-16 px-4 sm:px-6 lg:px-8 max-w-7xl mx-auto space-y-8">
      {/* ── HEADER ──────────────────────────────────────────────────────────── */}
      <div className="space-y-3">
        <span className="text-xs font-bold uppercase tracking-wider text-accent">
          Evidence-Linked Advice
        </span>
        <h1 className="text-3xl sm:text-4xl font-display font-bold text-text">
          Grounded Coaching Intelligence
        </h1>
        <p className="text-sm text-muted max-w-2xl">
          Every tip generated by the Coach Agent is backed by verified historical placement records.
          Click any citation chip to inspect the underlying archival precedent.
        </p>
      </div>

      {/* No Evidence Disclosure if triggered */}
      {noEvidenceNotice && (
        <div className="p-4 rounded-2xl bg-amber-500/10 border border-amber-500/30 text-amber-300 text-xs flex items-start space-x-3">
          <AlertCircle className="w-5 h-5 flex-shrink-0 text-amber-400 mt-0.5" />
          <div>
            <span className="font-bold block text-sm">General Guidance Disclosure</span>
            <p className="text-amber-200/90 mt-1">{noEvidenceNotice}</p>
          </div>
        </div>
      )}

      {/* ── TIPS LIST ───────────────────────────────────────────────────────── */}
      <div className="grid md:grid-cols-2 lg:grid-cols-3 gap-6">
        {tips.map((tip, idx) => (
          <GlassCard key={idx} className="p-6 flex flex-col justify-between space-y-4">
            <div className="space-y-3">
              <div className="flex items-center justify-between">
                <div className="w-8 h-8 rounded-xl bg-accent/15 text-accent flex items-center justify-center font-display font-bold text-xs">
                  {idx + 1}
                </div>
                <Lightbulb className="w-4 h-4 text-amber-400" />
              </div>
              <p className="text-xs sm:text-sm text-text/90 leading-relaxed font-medium">
                {tip.text}
              </p>
            </div>

            {/* Evidence Citations */}
            <div className="pt-3 border-t border-border/50 space-y-2">
              <span className="text-[10px] font-bold uppercase tracking-wider text-muted block">
                Historical Precedent Evidence:
              </span>
              <div className="flex flex-wrap gap-1.5">
                {tip.evidence_ids.map((eid) => (
                  <button
                    key={eid}
                    onClick={() => setSelectedRecordId(eid)}
                    className="inline-flex items-center px-2 py-1 rounded-lg text-[11px] font-mono font-semibold bg-accent/15 text-accent border border-accent/30 hover:bg-accent hover:text-white transition-all group"
                  >
                    <span>{eid}</span>
                    <ExternalLink className="w-3 h-3 ml-1 opacity-70 group-hover:opacity-100" />
                  </button>
                ))}
              </div>
            </div>
          </GlassCard>
        ))}
      </div>

      {/* ── ARCHIVE CITATION SLIDE-OVER DRAWER ──────────────────────────────── */}
      <AnimatePresence>
        {selectedRecordId && (
          <div className="fixed inset-0 z-50 flex justify-end bg-black/60 backdrop-blur-sm">
            <motion.div
              initial={{ opacity: 0, x: 400 }}
              animate={{ opacity: 1, x: 0 }}
              exit={{ opacity: 0, x: 400 }}
              transition={{ duration: 0.25, ease: 'easeOut' }}
              className="w-full max-w-lg h-full glass-panel-elevated p-6 overflow-y-auto space-y-6 border-l border-border shadow-2xl"
            >
              <div className="flex items-center justify-between border-b border-border/60 pb-4">
                <div className="flex items-center space-x-2">
                  <ShieldCheck className="w-5 h-5 text-emerald-400" />
                  <span className="font-display font-bold text-base text-text">
                    Archive Evidence Record
                  </span>
                </div>
                <button
                  onClick={() => setSelectedRecordId(null)}
                  className="p-1 rounded-xl text-muted hover:text-text hover:bg-white/10"
                >
                  <X className="w-5 h-5" />
                </button>
              </div>

              {isRecordLoading ? (
                <div className="py-20 text-center text-sm text-muted">
                  Loading archive record {selectedRecordId}...
                </div>
              ) : recordData ? (
                <div className="space-y-6 text-xs sm:text-sm">
                  {/* Record Header Badges */}
                  <div className="p-4 rounded-2xl bg-white/5 border border-white/10 space-y-2">
                    <div className="flex items-center justify-between">
                      <span className="font-mono font-bold text-accent text-sm">
                        {recordData.record_id}
                      </span>
                      <Badge
                        variant={recordData.outcome === 'Selected' ? 'success' : 'danger'}
                        size="sm"
                      >
                        Outcome: {recordData.outcome}
                      </Badge>
                    </div>
                    <div className="grid grid-cols-2 gap-2 text-xs text-muted pt-2 border-t border-border/40">
                      <div>Company: <strong className="text-text">{recordData.company}</strong></div>
                      <div>Year: <strong className="text-text">{recordData.year}</strong></div>
                      <div>Round: <strong className="text-text">{recordData.round_type}</strong></div>
                      <div>Topic: <strong className="text-text">{recordData.topic}</strong></div>
                    </div>
                  </div>

                  {/* Question */}
                  <div className="space-y-1.5">
                    <span className="text-[11px] font-bold uppercase tracking-wider text-muted block">
                      Archival Interview Question:
                    </span>
                    <p className="p-3.5 rounded-xl bg-white/5 border border-border text-text font-medium text-xs leading-relaxed">
                      {recordData.question}
                    </p>
                  </div>

                  {/* Candidate Summary */}
                  <div className="space-y-1.5">
                    <span className="text-[11px] font-bold uppercase tracking-wider text-muted block">
                      Candidate Answer Summary:
                    </span>
                    <p className="p-3.5 rounded-xl bg-white/5 border border-border text-text/80 text-xs leading-relaxed">
                      {recordData.candidate_answer_summary}
                    </p>
                  </div>

                  {/* Historical Evaluator Feedback */}
                  <div className="space-y-1.5">
                    <span className="text-[11px] font-bold uppercase tracking-wider text-accent block">
                      Actual Interviewer Feedback:
                    </span>
                    <p className="p-3.5 rounded-xl bg-accent/10 border border-accent/20 text-text text-xs italic leading-relaxed">
                      "{recordData.feedback_text}"
                    </p>
                  </div>

                  {/* Tags */}
                  <div className="space-y-1.5">
                    <span className="text-[11px] font-bold uppercase tracking-wider text-muted block">
                      Assigned Evaluation Tags:
                    </span>
                    <div className="flex flex-wrap gap-1.5">
                      {recordData.feedback_tags.map((t, i) => (
                        <span
                          key={i}
                          className="px-2 py-0.5 rounded-md bg-white/10 text-text text-[11px]"
                        >
                          #{t}
                        </span>
                      ))}
                    </div>
                  </div>
                </div>
              ) : (
                <div className="py-20 text-center text-sm text-rose-400">
                  Record '{selectedRecordId}' could not be retrieved from archive.
                </div>
              )}
            </motion.div>
          </div>
        )}
      </AnimatePresence>
    </div>
  )
}
